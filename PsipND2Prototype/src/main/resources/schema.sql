CREATE TABLE IF NOT EXISTS demo_context (
    tenant_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    planning_start TIMESTAMP WITH TIME ZONE,
    horizon_days INTEGER,
    stale BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (tenant_id, user_id)
);
CREATE TABLE IF NOT EXISTS task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000),
    tenant_id BIGINT NOT NULL,
    owner_user_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    deadline TIMESTAMP WITH TIME ZONE NOT NULL,
    priority VARCHAR(10) NOT NULL,
    remaining_minutes INTEGER NOT NULL,
    done BOOLEAN NOT NULL,
    PRIMARY KEY (id, tenant_id, owner_user_id),
    FOREIGN KEY (tenant_id, owner_user_id) REFERENCES demo_context(tenant_id, user_id)
);
CREATE TABLE IF NOT EXISTS availability (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000),
    tenant_id BIGINT NOT NULL,
    owner_user_id BIGINT NOT NULL,
    starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id, tenant_id, owner_user_id),
    FOREIGN KEY (tenant_id, owner_user_id) REFERENCES demo_context(tenant_id, user_id),
    CHECK (starts_at < ends_at)
);
CREATE TABLE IF NOT EXISTS work_session (
    tenant_id BIGINT NOT NULL,
    owner_user_id BIGINT NOT NULL,
    task_id BIGINT NOT NULL,
    starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (tenant_id, owner_user_id, starts_at),
    FOREIGN KEY (task_id, tenant_id, owner_user_id) REFERENCES task(id, tenant_id, owner_user_id) ON DELETE CASCADE,
    CHECK (starts_at < ends_at)
);
CREATE TABLE IF NOT EXISTS unscheduled_work (
    tenant_id BIGINT NOT NULL,
    owner_user_id BIGINT NOT NULL,
    task_id BIGINT NOT NULL,
    minutes INTEGER NOT NULL,
    reasons VARCHAR(2000) NOT NULL,
    PRIMARY KEY (tenant_id, owner_user_id, task_id),
    FOREIGN KEY (task_id, tenant_id, owner_user_id) REFERENCES task(id, tenant_id, owner_user_id) ON DELETE CASCADE,
    CHECK (minutes >= 0)
);
